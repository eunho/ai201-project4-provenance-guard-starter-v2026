import config


def combine_signals(
    model_score: float,
    style_score: float,
    repetition_score: float | None = None,
) -> float:
    """
    Combine signals into one 0–1 score. Higher means more likely AI.

    Args:
        model_score: from `detector.model_signal` — how predictable the text is.
        style_score: from `stylometry.style_signal` — the shape of the text.
        repetition_score: from `stylometry.repetition_signal` — token repetition & markers.

    Returns:
        A float from 0.0 (confidently human) to 1.0 (confidently AI).
    """
    if repetition_score is not None:
        raw = (
            config.WEIGHT_MODEL_SIGNAL * model_score
            + config.WEIGHT_STYLE_SIGNAL * style_score
            + getattr(config, "WEIGHT_REPETITION_SIGNAL", 0.20) * repetition_score
        )
    else:
        total = config.WEIGHT_MODEL_SIGNAL + config.WEIGHT_STYLE_SIGNAL
        w_model = config.WEIGHT_MODEL_SIGNAL / total
        w_style = config.WEIGHT_STYLE_SIGNAL / total
        raw = w_model * model_score + w_style * style_score

    return round(min(max(raw, 0.0), 1.0), 4)


def calculate_confidence(score: float, guess: str) -> float:
    """
    Calculate confidence in the guess on a 0.0–1.0 scale.
    Confidence varies with distance from decision boundaries.
    """
    if guess == "human":
        ratio = max(0.0, min(1.0, (config.HUMAN_THRESHOLD - score) / max(config.HUMAN_THRESHOLD, 0.01)))
        return round(0.70 + 0.30 * ratio, 2)
    elif guess == "ai":
        margin = max(1.0 - config.AI_THRESHOLD, 0.01)
        ratio = max(0.0, min(1.0, (score - config.AI_THRESHOLD) / margin))
        return round(0.70 + 0.30 * ratio, 2)
    else:
        mid = (config.HUMAN_THRESHOLD + config.AI_THRESHOLD) / 2.0
        dist = abs(score - mid)
        half_width = max((config.AI_THRESHOLD - config.HUMAN_THRESHOLD) / 2.0, 0.01)
        return round(0.40 + 0.25 * (dist / half_width), 2)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into a guess and the text a reader actually sees.

    Returns:
        (guess, label_text)
    """
    if score >= config.AI_THRESHOLD:
        return (
            "ai",
            "This writing closely matches the statistical predictability, uniform cadence, and formulaic phrasing commonly generated by AI language models.",
        )
    if score <= config.HUMAN_THRESHOLD:
        return (
            "human",
            "This writing displays the natural sentence rhythms, vocabulary variation, and expressive structure characteristic of an authentic human writer.",
        )
    return (
        "unsure",
        "We could not confidently determine whether this text is human-written or AI-generated, so no definitive automated verdict has been assigned.",
    )


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
